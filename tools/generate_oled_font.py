#!/usr/bin/env python3
"""Generate the project's small OLED glyph tables from an OFL CJK font.

Usage:
    python tools/generate_oled_font.py path/to/NotoSansCJKsc-Regular.otf

Requires Pillow. Only Chinese characters found in the OLED/application source
string literals are embedded; the font file itself is not copied into the repo.
"""

import hashlib
import re
import sys
from pathlib import Path

from PIL import Image, ImageFont


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Hardware" / "esp32" / "oled_font.c"
UI_SOURCES = [
    ROOT / "Services" / "src" / "ui_renderer.c",
    ROOT / "main" / "app_main.c",
]
STRING_LITERAL = re.compile(r'"(?:\\.|[^"\\])*"')


def used_chinese_characters():
    text = "\n".join(path.read_text(encoding="utf-8") for path in UI_SOURCES)
    literals = STRING_LITERAL.findall(text)
    chars = {
        char
        for literal in literals
        for char in literal
        if "\u4e00" <= char <= "\u9fff"
    }
    return sorted(chars, key=ord)


def normalized_bitmap(font, character, width, height):
    mask = font.getmask(character)
    if mask.size[0] == 0 or mask.size[1] == 0:
        return [[0] * width for _ in range(height)]
    image = Image.frombytes("L", mask.size, bytes(mask))
    image = image.resize((width, height), Image.ANTIALIAS)
    pixels = image.load()
    return [
        [1 if pixels[x, y] >= 96 else 0 for x in range(width)]
        for y in range(height)
    ]


def ascii_columns(font, character):
    rows = normalized_bitmap(font, character, 5, 7)
    columns = []
    for x in range(5):
        value = 0
        for y in range(7):
            if rows[y][x]:
                value |= 1 << y
        columns.append(value)
    return columns


def chinese_bytes(font, character):
    rows = normalized_bitmap(font, character, 16, 16)
    data = []
    for row in rows:
        for byte_index in range(2):
            value = 0
            for bit in range(8):
                if row[byte_index * 8 + bit]:
                    value |= 1 << (7 - bit)
            data.append(value)
    return data


def format_bytes(values, per_line=8):
    chunks = []
    for start in range(0, len(values), per_line):
        chunk = values[start:start + per_line]
        chunks.append("        " + ", ".join(f"0x{value:02X}" for value in chunk))
    return ",\n".join(chunks)


def generate(font_path):
    font_path = font_path.resolve()
    font_hash = hashlib.sha256(font_path.read_bytes()).hexdigest()
    ascii_font = ImageFont.truetype(str(font_path), 10)
    chinese_font = ImageFont.truetype(str(font_path), 16)
    chinese = used_chinese_characters()

    lines = [
        "/* Generated by tools/generate_oled_font.py.",
        " * 中文说明：下方是 OLED 用到的 ASCII 与中文字模，只存点阵，不存字体文件。",
        " * 每个字模在编译时成为只读数组；运行时按字符编码查表并复制到输出缓冲区。",
        " * Glyph bitmaps are derived from Noto Sans CJK SC,",
        " * Copyright 2014-2021 Adobe; SIL Open Font License 1.1.",
        f" * Source file: {font_path.name}; SHA-256: {font_hash}.",
        " * See OFL-Noto-Sans-CJK.txt in this directory.",
        " */",
        '#include "oled_font.h"',
        "",
        "#include <stddef.h>",
        "",
        "typedef struct { uint16_t codepoint; uint8_t bitmap[32]; } cn_glyph_t;",
        "",
        "/* ASCII 每个字符用 5 个列字节；每个中文字符用 32 字节表示 16×16 点阵。 */",
        "static const uint8_t ascii_font[95][5] = {",
    ]
    for codepoint in range(32, 127):
        character = chr(codepoint)
        columns = ascii_columns(ascii_font, character)
        values = ", ".join(f"0x{value:02X}" for value in columns)
        lines.append(f"    {{ {values} }}, /* U+{codepoint:04X} */")
    lines.extend(["};", "", "static const cn_glyph_t cn_font[] = {"])

    for character in chinese:
        values = chinese_bytes(chinese_font, character)
        lines.append(
            f"    {{ 0x{ord(character):04X}, {{\n{format_bytes(values)}\n"
            f"    }} }}, /* {character} */"
        )
    lines.extend([
        "};",
        "",
        "bool oled_font_get_ascii(char value, uint8_t out[5])",
        "{",
        "    /* out 是调用者给出的 5 字节缓冲区，逐列复制对应 ASCII 点阵。 */",
        "    if (out == NULL || value < 32 || value > 126) return false;",
        "    const unsigned index = (unsigned)((unsigned char)value - 32U);",
        "    for (unsigned i = 0U; i < 5U; ++i) out[i] = ascii_font[index][i];",
        "    return true;",
        "}",
        "",
        "bool oled_font_get_chinese(uint16_t codepoint, uint8_t out[32])",
        "{",
        "    /* 中文字符按 Unicode 编码查表；没生成的字返回 false。 */",
        "    if (out == NULL) return false;",
        "    for (size_t i = 0U; i < sizeof(cn_font) / sizeof(cn_font[0]); ++i) {",
        "        if (cn_font[i].codepoint == codepoint) {",
        "            for (size_t j = 0U; j < 32U; ++j) out[j] = cn_font[i].bitmap[j];",
        "            return true;",
        "        }",
        "    }",
        "    return false;",
        "}",
        "",
    ])
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(chinese)} Chinese glyphs: {OUTPUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: python generate_oled_font.py PATH_TO_OFL_CJK_FONT")
    generate(Path(sys.argv[1]))
